def main():
    base_dir = "frontend/assets/i18n"
    # Read existing files
    current_data = {}
    for lang in LANGUAGES:
        path = os.path.join(base_dir, f"{lang}.json")
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                current_data[lang] = json.load(f)
        else:
            current_data[lang] = {}

    # Merge our new translations
    for item in TRANSLATIONS:
        en_key = item.get("en")
        de_key = item.get("de")

        for lang in LANGUAGES:
            trans_val = item.get(lang, item.get("en", ""))
            if not trans_val:
                continue

            # Set with English key
            if en_key:
                current_data[lang][en_key] = trans_val
            # Set with German key
            if de_key:
                current_data[lang][de_key] = trans_val

    # Also for all existing keys in de.json:
    # Ensure they map properly
    for lang in LANGUAGES:
        out_path = os.path.join(base_dir, f"{lang}.json")
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(current_data[lang], f, ensure_ascii=False, indent=2)
        print(f"Wrote {out_path}: {len(current_data[lang])} keys")

if __name__ == "__main__":
    main()
