def main():
    base_dir = "frontend/assets/i18n"
    # Load all existing language JSONs
    data = {}
    for lang in LANGUAGES:
        path = os.path.join(base_dir, f"{lang}.json")
        with open(path, "r", encoding="utf-8") as f:
            data[lang] = json.load(f)

    # Overwrite/merge new items
    for item in NEW_ITEMS:
        en_key = item.get("en")
        de_key = item.get("de")

        for lang in LANGUAGES:
            trans_val = item.get(lang, en_key)
            if not trans_val:
                continue
            if en_key:
                data[lang][en_key] = trans_val
            if de_key:
                data[lang][de_key] = trans_val

    # Ensure en.json does not map German keys to German text if English translation is available
    for item in NEW_ITEMS:
        de_key = item.get("de")
        en_val = item.get("en")
        if de_key and en_val:
            data["en"][de_key] = en_val

    # Write back all files
    for lang in LANGUAGES:
        path = os.path.join(base_dir, f"{lang}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data[lang], f, ensure_ascii=False, indent=2)
        print(f"Updated {path} ({len(data[lang])} keys)")

if __name__ == "__main__":
    main()
